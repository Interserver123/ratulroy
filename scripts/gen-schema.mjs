#!/usr/bin/env node
// Regenerates backend/lib/schema.ts from migrations/*.sql so the self-initialising
// database (no command line needed) always matches the Wrangler migrations.
//   node scripts/gen-schema.mjs        (run after adding or editing a migration)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../migrations/", import.meta.url);
const files = readdirSync(dir).filter((f) => /^\d+_.+\.sql$/.test(f)).sort();

function statements(sql) {
  const clean = sql.replace(/--.*$/gm, "");
  const out = [];
  let buf = "";
  let inTrigger = false;
  for (const line of clean.split("\n")) {
    buf += line + "\n";
    if (/\bBEGIN\s*$/i.test(line.trim())) inTrigger = true;
    if (inTrigger ? /^\s*END;\s*$/i.test(line) : /;\s*$/.test(line)) {
      const s = buf.trim().replace(/;$/, "").replace(/\s+/g, " ").trim();
      if (s && !/^PRAGMA/i.test(s)) out.push(s);
      buf = "";
      inTrigger = false;
    }
  }
  return out;
}

const groups = files.map((f) => {
  const st = statements(readFileSync(new URL(f, dir), "utf8"));
  const tables = st.map((s) => s.match(/^CREATE (?:VIRTUAL )?TABLE IF NOT EXISTS (\w+)/i)?.[1]).filter(Boolean);
  return { file: f, sentinel: tables[tables.length - 1], statements: st };
});

const body = groups
  .map((g) => `  {\n    file: ${JSON.stringify(g.file)},\n    sentinel: ${JSON.stringify(g.sentinel)},\n    statements: [\n${g.statements.map((s) => `      ${JSON.stringify(s)},`).join("\n")}\n    ],\n  },`)
  .join("\n");

writeFileSync(
  new URL("../backend/lib/schema.ts", import.meta.url),
  `// GENERATED by scripts/gen-schema.mjs from migrations/*.sql. Do not edit by hand.
// Creates any missing tables on first use, so setup needs no command line.
// Every statement is "IF NOT EXISTS", so running it again is harmless.
import type { Env } from "./types";

export const MIGRATIONS: { file: string; sentinel: string; statements: string[] }[] = [
${body}
];

let ready = false;

export async function ensureSchema(env: Env) {
  if (ready) return;
  for (const m of MIGRATIONS) {
    const exists = await env.DB.prepare("SELECT name FROM sqlite_master WHERE name = ?").bind(m.sentinel).first();
    if (!exists) await env.DB.batch(m.statements.map((s) => env.DB.prepare(s)));
  }
  ready = true;
}
`,
);
console.log(groups.map((g) => `${g.file}: ${g.statements.length} statements (sentinel ${g.sentinel})`).join("\n"));
